    private void ieladetEdienkarti() {

        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel)
            edienkarteTable.getModel();

        model.setRowCount(0);

        DishesDao dishesDao = new DishesDao();

        try (Connection conn = DatabaseManager.getConnection()){
            List<Object[]> ediensData = dishesDao.ieladetEdienkarti();
            if (ediensData != null) {
            for (Object[] ediens : ediensData){
                model.addRow(ediens);
            }}else{
                JOptionPane.showMessageDialog(
                this,
                "Nav atrasti neviena ēdiena.",
                "Informācija",
                JOptionPane.INFORMATION_MESSAGE
            );
        }
            
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(
                this,
                "Neizdevās ielādēt ēdienkarti:\n" + ex.getMessage(),
                "Datubāzes kļūda",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }
    
