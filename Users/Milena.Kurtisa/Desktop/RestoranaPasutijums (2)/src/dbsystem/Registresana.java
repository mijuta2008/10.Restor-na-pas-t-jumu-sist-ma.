    private void maksatButActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_maksatButActionPerformed
        // TODO add your handling code here:
        if (currentUserId == 0) {
            JOptionPane.showMessageDialog(this,"Vispirms ielogojieties!");
            return;
        }

        if (currentOrderId == 0) {
            JOptionPane.showMessageDialog(this,"Grozs ir tukšs!");
            return;
        }

        // norādiet rezervācijas datumu
        String dateText = JOptionPane.showInputDialog(
            this,
            "Ievadiet rezervācijas datumu:"
        );

        if (dateText == null) return;

        // norādiet rezervācijas laiku
        String timeText = JOptionPane.showInputDialog(
            this,
            "Ievadiet rezervācijas laiku:"
        );

        if (timeText == null) return;

        java.sql.Date reservationDate;
        java.sql.Time reservationTime;

        try {
            String normalizedDate = dateText.trim();
            java.time.LocalDate parsedDate;

            java.time.format.DateTimeFormatter formatter =
                java.time.format.DateTimeFormatter.ofPattern("dd.MM.uuuu");

            if (normalizedDate.matches("\\d{2}\\.\\d{2}")) {
                normalizedDate += "." + java.time.LocalDate.now().getYear();
            }

            if (normalizedDate.matches("\\d{2}\\.\\d{2}\\.\\d{4}")) {
                parsedDate = java.time.LocalDate.parse(
                    normalizedDate, formatter
                );
            } else if (normalizedDate.matches("\\d{4}-\\d{2}-\\d{2}")) {
                parsedDate = java.time.LocalDate.parse(normalizedDate);
            } else {
                throw new IllegalArgumentException("Nepareizs datums");
            }

            reservationDate = java.sql.Date.valueOf(parsedDate);

            // laiks 17:00 vai 17:00:00
            String normalizedTime = timeText.trim();

            if (normalizedTime.matches("\\d{2}:\\d{2}")) {
                normalizedTime += ":00";
            }

            reservationTime = java.sql.Time.valueOf(normalizedTime);

            // nepieļaujam pagātnes datumus.
            if (reservationDate.before(
                    new java.sql.Date(System.currentTimeMillis()))) {

                JOptionPane.showMessageDialog(
                    this, "Rezervācijas datums nevar būt pagātnē!"
                );
                return;
            }

        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(
                this,
                "Nepareizs datums vai laiks!\n"
                + "Datums: 29.10 vai 29.10.2026\n"
                + "Laiks: 17:00:00",
                "Kļūda",
                JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        try (Connection conn = DatabaseManager.getConnection()) {

            conn.setAutoCommit(false);

            try {
                // pārbaudām, vai pasūtījumā ir ēdieni
                String checkSql =
                    "SELECT COUNT(*) FROM ORDER_DISHES " + "WHERE ORDER_ID = ?";

                int count;

                try (PreparedStatement ps = conn.prepareStatement(checkSql)) {

                    ps.setInt(1, currentOrderId);

                    try (ResultSet rs = ps.executeQuery()) {
                        rs.next();
                        count = rs.getInt(1);
                    }
                }

                if (count == 0) {
                    conn.rollback();
                    JOptionPane.showMessageDialog(this,
                        "Grozs ir tukšs!");
                    return;
                }

                // vai pasūtījums pieder lietotājam.
                String checkOrderSql =
                    "SELECT ORDER_ID FROM ORDERS "
                    + "WHERE ORDER_ID = ? AND USER_ID = ?";

                try (PreparedStatement ps = conn.prepareStatement(checkOrderSql)) {

                    ps.setInt(1, currentOrderId);
                    ps.setInt(2, currentUserId);

                    try (ResultSet rs = ps.executeQuery()) {
                        if (!rs.next()) {
                            throw new SQLException(
                                "Pasūtījums nav atrasts!"
                            );
                        }
                    }
                }

                // Rezervācijas saglabāšana
                String reservationSql = 
                    "INSERT INTO RESERVATIONS"
                    + "(RESERVATION_DATE, RESERVATION_TIME, STATUS, USER_ID) "
                    + "VALUES (?, ?, ?, ?)";

                try (PreparedStatement ps = conn.prepareStatement(reservationSql)) {

                    ps.setDate(1, reservationDate);
                    ps.setTime(2, reservationTime);
                    ps.setBoolean(3, true);
                    ps.setInt(4, currentUserId);

                    ps.executeUpdate();
                }

                // Pasūtījuma apstiprināšana
                String updateSql =
                    "UPDATE ORDERS "
                    + "SET STATUS = ?, PAYMENT_STATUS = ? "
                    + "WHERE ORDER_ID = ? AND USER_ID = ?";

                try (PreparedStatement ps = conn.prepareStatement(updateSql)) {

                    ps.setString(1, "Pabeigts");
                    ps.setBoolean(2, true);
                    ps.setInt(3, currentOrderId);
                    ps.setInt(4, currentUserId);

                    if (ps.executeUpdate() != 1) {
                        throw new SQLException(
                            "Neizdevās apstiprināt pasūtījumu!"
                        );
                    }
                }

                conn.commit();

                JOptionPane.showMessageDialog(this,
                    "Pasūtījums un rezervācija veiksmīgi noformēti!\n\n"
                    + "Pasūtījuma numurs: " + currentOrderId + "\n"
                    + "Rezervācijas numurs: " + "\n"
                    + "Datums: " + reservationDate + "\n"
                    + "Laiks: " + reservationTime + "\n\n",
                    "Informācija",
                    JOptionPane.INFORMATION_MESSAGE
                );
                
                //tukšošana grozu
                currentOrderId = 0;

                javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel)
                pasutijumaGrozs.getModel();

                model.setRowCount(0);
                summaText.setText("0.00");

            } catch (SQLException ex) {
                conn.rollback();
                throw ex;
            } finally {
                conn.setAutoCommit(true);
            }

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this,
                "Datubāzes kļūda: " + ex.getMessage(),
                "Kļūda",
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_maksatButActionPerformed

