    private void updateCartTable() throws SQLException {

        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel)
            pasutijumaGrozs.getModel();

        model.setRowCount(0);

        String sql =
            "SELECT d.DISH_ID, d.NAME, od.QUANTITY, od.PRICE "
            + "FROM ORDER_DISHES od "
            + "JOIN DISHES d ON d.DISH_ID = od.DISH_ID "
            + "WHERE od.ORDER_ID = ?";

        try (Connection conn = DatabaseManager.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {

            ps.setInt(1, currentOrderId);

            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    model.addRow(new Object[]{
                        rs.getInt("DISH_ID"),
                        rs.getString("NAME"),
                        rs.getInt("QUANTITY"),
                        rs.getBigDecimal("PRICE")
                    });
                }
            }
        }

    // Pārrēķina pasūtījuma kopējo summu
    OrderDao orderDao = new OrderDao();
    BigDecimal total = orderDao.updateTotal(currentOrderId);

    summaText.setText(total.toPlainString());
}
    
